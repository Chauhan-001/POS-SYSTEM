import { Request, Response } from 'express';
import {
  salesReportService, productReportService, inventoryReportService,
  employeeReportService, closingReportService, branchReportService, summaryService,
} from '../services';
import { exportService, ExportMeta, ExportTable } from '../services/exportService';
import type { ReportScope, ReportUser } from '../types';

function userOf(req: Request): ReportUser {
  const u = (req as any).user as ReportUser | undefined;
  return u || { restaurantId: '' };
}

function scopeOf(req: Request): ReportScope {
  const user = userOf(req);
  const q = req.query as Record<string, string | undefined>;
  return {
    restaurantId: user.restaurantId,
    branchId: q.branchId || user.branchId,
    startDate: q.startDate,
    endDate: q.endDate,
    openingTime: q.openingTime,
  };
}

function ok(res: Response, data: unknown): void {
  res.json({ data });
}

/** Build shared export meta from the request scope. */
function exportMeta(req: Request, title: string, scope: ReportScope): ExportMeta {
  const user = userOf(req);
  return {
    title,
    generatedAt: new Date().toISOString(),
    filters: {
      'Date Range': `${scope.startDate || 'all'} → ${scope.endDate || 'all'}`,
      Restaurant: user.restaurantId || '—',
      Branch: scope.branchId || 'All',
    },
    footer: 'Generated by POS Reports Engine',
  };
}

function extractTable(payload: any): ExportTable {
  if (Array.isArray(payload)) {
    const headers = payload.length ? Object.keys(payload[0]) : ['Value'];
    return { headers, rows: payload.map((r) => headers.map((h) => r[h] ?? '')) };
  }
  const keys = Object.keys(payload || {});
  return {
    headers: ['Key', 'Value'],
    rows: keys.map((k) => [k, typeof payload[k] === 'object' ? JSON.stringify(payload[k]) : String(payload[k] ?? '')]),
  };
}

