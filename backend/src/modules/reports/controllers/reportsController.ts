// ─── Exports (Owner/Manager only) ────────────────────────────────

export async function exportReport(req: Request, res: Response): Promise<void> {
  const scope = scopeOf(req);
  const format = (req.query.format as 'csv' | 'xlsx' | 'pdf') || 'csv';
  const report = req.query.report as string;
  const title = `Report - ${report}`;

  let payload: unknown;
  switch (report) {
    case 'sales': payload = await salesReportService.summary(scope); break;
    case 'products': payload = await productReportService.top(scope, 100); break;
    case 'inventory': payload = await inventoryReportService.stock(scope); break;
    case 'employees': payload = await employeeReportService.performance(scope); break;
    case 'payments': payload = await salesReportService.payments(scope); break;
    case 'categories': payload = await productReportService.categories(scope); break;
    case 'branch': payload = await branchReportService.branchSummary(scope); break;
    default: res.status(400).json({ error: `Unknown report: ${report}` }); return;
  }

  const table = extractTable(payload);
  const meta = exportMeta(req, title, scope);
  const headers = exportService.exportHeaders(format, title);
  res.set(headers);

  if (format === 'csv') {
    const stream = exportService.streamCsv(table, meta);
    stream.pipe(res);
    return;
  }
  if (format === 'xlsx') {
    res.send(await exportService.buildXlsx(table, meta));
    return;
  }
  res.send(await exportService.buildPdf(table, meta));
}
